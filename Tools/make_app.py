"""Build the double-clickable SatAi.app bundle (no Swift, no Xcode).

What it does:
1. Loads the user's circular mission-badge logo from
   ``assets/branding/SatAI_logo.png`` (the brand source of truth),
   centers it on a square transparent canvas and exports the full macOS
   iconset (16..1024 px) converted to ``SatAi.icns`` via ``iconutil``.
   A 64 px copy is also written to ``App/ui/logo.png`` for the UI header.
2. Assembles ``SatAi.app``: ``Info.plist`` + launcher script that runs
   ``.venv/bin/python -m App`` from the project root.

Run: ``python Tools/make_app.py`` — rerun it any time to rebuild.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
ASSETS_DIR = PROJECT_ROOT / "assets"
BRAND_LOGO = ASSETS_DIR / "branding" / "SatAI_logo.png"
UI_LOGO = PROJECT_ROOT / "App" / "ui" / "logo.png"
APP_DIR = PROJECT_ROOT / "SatAi.app"
ICON_SIZE = 1024


# ---------------------------------------------------------------------------
# 1. Icon set from the user's circular badge logo
# ---------------------------------------------------------------------------
def _load_logo_square() -> "Image.Image":  # noqa: F821 — PIL imported lazily
    """Return the logo centered on a square transparent canvas at full res."""
    from PIL import Image, ImageOps

    if not BRAND_LOGO.exists():
        raise SystemExit(
            f"Logo non trovato: {BRAND_LOGO}\n"
            "Metti il PNG del logo in assets/branding/SatAI_logo.png "
            "e rilancia lo script.")
    logo = Image.open(BRAND_LOGO).convert("RGBA")
    # Center the (nearly square) circle on a perfectly square canvas so the
    # badge stays circular and centered at every icon size.
    side = max(logo.size)
    canvas = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    canvas.paste(logo, ((side - logo.width) // 2, (side - logo.height) // 2),
                 logo)
    ImageOps.exif_transpose(canvas)
    return canvas


def build_iconset(icns_dest: Path) -> None:
    """Export every needed size from the logo and convert to .icns."""
    from PIL import Image

    iconset = ASSETS_DIR / "SatAi.iconset"
    if iconset.exists():
        shutil.rmtree(iconset)
    iconset.mkdir(parents=True)

    base = _load_logo_square()
    big = ASSETS_DIR / "icon_1024.png"
    base.resize((ICON_SIZE, ICON_SIZE), Image.LANCZOS).save(big)

    for sz in (16, 32, 128, 256, 512):
        for name, px in ((f"icon_{sz}x{sz}.png", sz),
                         (f"icon_{sz}x{sz}@2x.png", sz * 2)):
            base.resize((px, px), Image.LANCZOS).save(iconset / name)

    # Small copy for the UI header (rendered next to the title at ~17 px,
    # 64 px gives the retina display 2x and 4x headroom).
    UI_LOGO.parent.mkdir(parents=True, exist_ok=True)
    base.resize((64, 64), Image.LANCZOS).save(UI_LOGO)

    subprocess.run(["iconutil", "-c", "icns", str(iconset),
                    "-o", str(icns_dest)], check=True)


# ---------------------------------------------------------------------------
# 2. The .app bundle (Info.plist + launcher script)
# ---------------------------------------------------------------------------
INFO_PLIST = """<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" \
"http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>SatAi</string>
  <key>CFBundleDisplayName</key><string>SatAi</string>
  <key>CFBundleIdentifier</key><string>org.satai.desktop</string>
  <key>CFBundleVersion</key><string>1.1</string>
  <key>CFBundleShortVersionString</key><string>1.1</string>
  <key>CFBundleExecutable</key><string>SatAi</string>
  <key>CFBundleIconFile</key><string>SatAi</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>NSHighResolutionCapable</key><true/>
  <key>LSApplicationCategoryType</key><string>public.app-category.utilities</string>
  <key>NSPrincipalClass</key><string>NSApplication</string>
</dict>
</plist>
"""


def build_app(project_root: Path) -> None:
    """Assemble SatAi.app with a launcher bound to this machine's venv."""
    if APP_DIR.exists():
        shutil.rmtree(APP_DIR)
    (APP_DIR / "Contents" / "MacOS").mkdir(parents=True)
    (APP_DIR / "Contents" / "Resources").mkdir(parents=True)

    (APP_DIR / "Contents" / "Info.plist").write_text(INFO_PLIST, encoding="utf-8")
    build_iconset(APP_DIR / "Contents" / "Resources" / "SatAi.icns")

    # The absolute project path is baked in at build time, so the bundle
    # keeps working even if moved to /Applications or the Dock.
    launcher = f"""#!/bin/bash
# SatAi launcher (generated by Tools/make_app.py)
ROOT="{project_root}"
if [ ! -x "$ROOT/.venv/bin/python" ]; then
  /usr/bin/osascript -e 'display dialog "SatAi: virtualenv non trovato in\\n$ROOT/.venv\\n\\nRigenera il bundle con: python Tools/make_app.py" with title "SatAi" buttons {{"OK"}} default button "OK" with icon stop'
  exit 1
fi
cd "$ROOT" || exit 1
exec "$ROOT/.venv/bin/python" -m App "$@"
"""
    exe = APP_DIR / "Contents" / "MacOS" / "SatAi"
    exe.write_text(launcher, encoding="utf-8")
    exe.chmod(0o755)


def main() -> int:
    """Build icon + bundle and verify the plist."""
    print(f"Building iconset from {BRAND_LOGO.name} …")
    build_app(PROJECT_ROOT)

    plist = APP_DIR / "Contents" / "Info.plist"
    lint = subprocess.run(["plutil", "-lint", str(plist)],
                          capture_output=True, text=True)
    print(lint.stdout.strip())

    print(f"Built: {APP_DIR}")
    print(f"UI header logo: {UI_LOGO}")
    print("Drag it wherever you like (folder, Dock, Applications).")
    return 0 if lint.returncode == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
